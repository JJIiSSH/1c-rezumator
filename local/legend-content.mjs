// Validate only newly generated learner-facing material; legacy drafts remain editable.
const editorial=[
 /(?:нужно|необходимо|требуется)\s+(?:уточнить|сверить|подтвердить)/iu,
 /(?:нужен|нужны)\s+(?:мой|мои|его|её)?\s*фактическ[а-яё]*\s+(?:ответ|данн)/iu,
 /(?:не могу|не буду)\s+(?:придумать|выдумывать|придумывать|предложить ответ)/iu,
 /(?:придумывать|выдумывать).{0,35}(?:нельзя|запрещено)/iu,
 /(?:в исходных данных|в исходнике).{0,60}(?:не указан|отсутств|нет сведений)/iu,
 /(?:причина|мотив|опыт).{0,45}(?:не указан|не подтверждён|не подтвержден)/iu,
 /(?:по резюме|в резюме указано|я указан в резюме|мой вклад по резюме)/iu,
 /предложенн[а-яё]*\s+тестов[а-яё]*\s+сценар/iu,
 /(?:сверить|согласовать).{0,30}(?:с моим опытом|с учеником|с кандидатом)/iu
];
export function legendEditorialLeaks(text){return String(text||'').split('\n').map(line=>line.trim()).filter(line=>editorial.some(pattern=>pattern.test(line.replace(/(?:нужно|необходимо|требуется)\s+уточнить\s+(?:требования|бизнес-правила|правила|формат обмена|реквизиты)(?=[\s.,:;]|$)/giu,'[уточнение требований]'))));}
export function assertReadyLegend(text){if(legendEditorialLeaks(text).length)throw Error('В легенде остались служебные замечания вместо готовых ответов. Прежняя версия сохранена; повторите генерацию.');return text;}
